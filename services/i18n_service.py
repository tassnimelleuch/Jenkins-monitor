def get_dashboard_language_choices():
    return DASHBOARD_LANGUAGE_CHOICES


def normalize_dashboard_language(value, default=DEFAULT_DASHBOARD_LANGUAGE):
    normalized = (value or '').strip().lower()
    if normalized in DASHBOARD_LOCALES:
        return normalized
    return default


def get_dashboard_locale(language):
    normalized = normalize_dashboard_language(language)
    return DASHBOARD_LOCALES.get(normalized, DASHBOARD_LOCALES[DEFAULT_DASHBOARD_LANGUAGE])


def get_dashboard_direction(language):
    normalized = normalize_dashboard_language(language)
    return 'rtl' if normalized in RTL_LANGUAGES else 'ltr'


def get_translations(language):
    normalized = normalize_dashboard_language(language)
    base = TRANSLATIONS[DEFAULT_DASHBOARD_LANGUAGE]
    if normalized == DEFAULT_DASHBOARD_LANGUAGE:
        return base

    selected = TRANSLATIONS.get(normalized, {})
    return {
        key: selected.get(key, value)
        for key, value in base.items()
    }


def translate(key, language=None, **kwargs):
    message = get_translations(language).get(key, key)
    if kwargs:
        try:
            return message.format(**kwargs)
        except (IndexError, KeyError, ValueError):
            return message
    return message
